package ru.polyclinic.queue.model;

/**
 * Маркер редактируемости. Реализуют только талоны, которые можно создавать
 * через «Добавить» и менять через «Изменить»: {@link Ticket} (обычный) и
 * {@link HomeVisitTicket}. {@link ClosedTicket} — read-only, интерфейс не
 * реализует: проверка {@code ticket instanceof Editable} — единый способ
 * отличить редактируемый талон от архивного (в GUI и сервисе).
 */
public interface Editable {

    /**
     * Возвращает список нарушений (пустой список = объект корректен).
     * Одна ошибка — одна человекочитаемая строка; бросать исключение здесь не принято.
     * Реализация есть в базовом Ticket, поэтому наследники её уже получают.
     */
    java.util.List<String> validate();

    // Примечание: копия с изменениями называется withChanges(...) и уже
    // переопределена в Ticket/HomeVisitTicket — отдельный метод copyWith
    // вводить не нужно, иначе наследники пришлось бы править дважды.
}